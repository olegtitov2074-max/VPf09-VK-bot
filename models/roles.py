DEFAULT_ROLE_KEY = "assistant"


def get_role(key: str) -> Role:
    """Возвращает роль по ключу. Если ключ неизвестен — дефолт."""
    return ROLES.get(key, ROLES[DEFAULT_ROLE_KEY])


def role_list() -> list[Role]:
    """Список всех ролей в порядке объявления."""
    return list(ROLES.values())